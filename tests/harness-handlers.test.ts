import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { Harness } from '../src/server/harness.js';
import { harnessHandlers } from '../src/server/ws/handlers/harness.js';

test('authenticated Harness handler retains admin gating, correlated failures and source-only restore', (t) => {
  const dir = mkdtempSync(path.join(tmpdir(), 'harness-handler-')), root = path.join(dir, 'source'), data = path.join(dir, 'data');
  mkdirSync(root); mkdirSync(data); writeFileSync(path.join(root, 'CLAUDE.md'), 'Original source');
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const homes = { claude: path.join(dir, 'claude'), kimi: path.join(dir, 'kimi'), codex: path.join(dir, 'codex') };
  const harness = new Harness(data, root, () => homes, () => {}), sent: any[] = [];
  let admin = false;
  const ctx: any = { harness, meOf: () => ({ admin }), sendTo: (_c: unknown, msg: unknown) => sent.push(msg), warn() {} };
  const client: any = { accountId: 'fixture', peer: { name: 'Jonathan' } };
  const invoke = (name: keyof typeof harnessHandlers, msg: any) => { (harnessHandlers[name] as any)(ctx, client, msg); return sent.at(-1); };
  const base = harness.read('CLAUDE.md').revision;
  assert.match(invoke('harness.write', { path: 'CLAUDE.md', text: 'Denied', base, request: 'one' }).error, /Only admins/);
  assert.match(invoke('harness.restore', { path: 'CLAUDE.md', base, revision: 'x', request: 'two' }).error, /Only admins/);
  assert.equal(readFileSync(path.join(root, 'CLAUDE.md'), 'utf8'), 'Original source');
  const read = invoke('harness.read', { path: 'CLAUDE.md', request: 'read' });
  assert.equal(read.request, 'read'); assert.equal(read.text, 'Original source');
  admin = true;
  assert.match(invoke('harness.write', { path: 'CLAUDE.md', text: 'No base', request: 'missing' }).error, /content revision/);
  const saved = invoke('harness.write', { path: 'CLAUDE.md', text: 'Edited', base, request: 'save' });
  assert.equal(saved.request, 'save'); assert.equal(saved.file.text, 'Edited');
  const history = invoke('harness.history', { path: 'CLAUDE.md', request: 'history' }).history;
  const entry = history.revisions[0];
  assert.equal(entry.by, 'Jonathan');
  const snapshot = invoke('harness.snapshot', { path: 'CLAUDE.md', revision: entry.id, request: 'snapshot' }).snapshot;
  assert.equal(snapshot.text, 'Original source');
  assert.ok(invoke('harness.snapshot', { path: '../CLAUDE.md', revision: entry.id, request: 'escape' }).error);
  assert.ok(invoke('harness.restore', { path: 'CLAUDE.md', base, revision: entry.id, request: 'stale' }).error);
  const restored = invoke('harness.restore', { path: 'CLAUDE.md', base: saved.file.revision, revision: entry.id, request: 'restore' });
  assert.equal(restored.file.text, 'Original source');
  assert.equal(harness.state().applied, undefined);
  for (const home of Object.values(homes)) assert.equal(existsSync(home), false);
});
