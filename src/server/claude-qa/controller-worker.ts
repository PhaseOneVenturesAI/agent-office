// Root-owned, bundled entry point. Only the controller's private stdin supplies selected credentials.
import { pathToFileURL } from 'node:url';
import { CLAUDE_QA_MODEL, qualifyJob } from './policy.js';
import { runClaudeQaIsolated } from './runtime.js';
import { unavailablePolicy, type QualifySelectedPolicy, type SelectedClaudeAccount } from './controller-policy.js';

export const CONTROLLER_IMAGE = '/var/lib/agent-office-claude-qa/image';
export interface ControllerRequest { v: 1; requestId: string; custodianAccountId: string; prompt: string }
export interface WorkerInput { request: ControllerRequest; selected: SelectedClaudeAccount; runtimeId: string }
type Runtime = (options: Parameters<typeof runClaudeQaIsolated>[0] & { runtimeId: string }) => ReturnType<typeof runClaudeQaIsolated>;
const unavailable = () => ({ ok: false as const, code: 'unavailable' as const });

/** Injection is trusted code only. Nothing on the Unix wire can choose a qualifier or runtime. */
export async function executeControllerJob(input: WorkerInput, deps: { qualify?: QualifySelectedPolicy; run?: Runtime } = {}) {
  const abort = new AbortController(), timer = setTimeout(() => abort.abort(), 120_000);
  try {
    const { request, selected, runtimeId } = input;
    if (request.v !== 1 || !/^[a-f0-9]{32}$/.test(request.requestId) || !/^[a-f0-9]{16}$/.test(request.custodianAccountId) || request.custodianAccountId !== selected.accountId || !/^[a-f0-9]{12}$/.test(runtimeId)) return unavailable();
    if (typeof request.prompt !== 'string' || !request.prompt.trim() || Buffer.byteLength(request.prompt) > 64_000) return unavailable();
    if (!selected.accessToken.startsWith('sk-ant-oat') || selected.oauthAccount.expiresAt <= Date.now() + 150_000 || !selected.oauthAccount.scopes.includes('user:inference')) return unavailable();
    const policy = await (deps.qualify ?? unavailablePolicy)({ ...selected, signal: abort.signal });
    if (!policy || abort.signal.aborted) return unavailable();
    const job = { accountId: selected.accountId, model: CLAUDE_QA_MODEL, prompt: request.prompt, policy };
    qualifyJob(job);
    // runtimeId is generated by root, not requestId. The reviewed runtime must honor it for cleanup.
    const outcome = await (deps.run ?? runClaudeQaIsolated)({ image: CONTROLLER_IMAGE, job, accessToken: selected.accessToken, runtimeSeconds: 100, runtimeId });
    return outcome.ok && typeof outcome.answer === 'string' && outcome.answer.trim() && !abort.signal.aborted ? { ok: true as const, answer: outcome.answer } : unavailable();
  } catch { return unavailable(); }
  finally { clearTimeout(timer); abort.abort(); }
}

async function main() {
  if (process.getuid?.() !== 0 || process.platform !== 'linux' || process.argv.length !== 2) throw new Error('Fixed root entry point required.');
  const chunks: Buffer[] = []; let bytes = 0;
  for await (const chunk of process.stdin) { bytes += chunk.length; if (bytes > 160_000) throw new Error('Input limit.'); chunks.push(Buffer.from(chunk)); }
  const result = await executeControllerJob(JSON.parse(Buffer.concat(chunks).toString()));
  process.stdout.write(JSON.stringify(result));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) void main().catch(() => { process.stdout.write(JSON.stringify(unavailable())); process.exitCode = 1; });
